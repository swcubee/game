// Builds js/pictures.js from the picture files in pictures/, in file name order (01-..., 02-...).
// The order is the order of play: pictures grow in cell count (rule from Дион, design/progression.md).
// Picture file: { id, name: {ru, en}, palette: ["#rrggbb", ...], regions: [{ id, c, d, nx, ny }], decorBack, decorFront }
//   regions: one paintable cell each; c = colour index into the palette; nx/ny = where the number sits.
//   decorBack / decorFront: lines and shapes drawn under / over the cells ({ d, s, fill, top, light, g }).
// The art comes from the art coordinator (ChatGPT drawings converted to this format).
// Run: node tools/build-pictures.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../pictures/', import.meta.url);
const files = readdirSync(dir).filter(f => /^\d+-.+\.json$/.test(f)).sort();
const pictures = [], problems = [];
for (const f of files) {
  const p = JSON.parse(readFileSync(new URL(f, dir), 'utf8'));
  const where = `${f}:`;
  if (!p.id || !p.name || !p.name.ru || !p.name.en) problems.push(`${where} id and name.ru/name.en are required`);
  if (!Array.isArray(p.palette) || p.palette.length < 2 || p.palette.length > 8) problems.push(`${where} palette must have 2..8 colours`);
  (p.palette || []).forEach(c => { if (!/^#[0-9a-fA-F]{6}$/.test(c)) problems.push(`${where} bad colour ${c}`); });
  const ids = new Set();
  for (const r of p.regions || []) {
    if (ids.has(r.id)) problems.push(`${where} duplicate cell id ${r.id}`);
    ids.add(r.id);
    if (!(r.c >= 0 && r.c < p.palette.length)) problems.push(`${where} cell ${r.id} has colour ${r.c} outside the palette`);
    if (typeof r.d !== 'string' || !isFinite(r.nx) || !isFinite(r.ny)) problems.push(`${where} cell ${r.id} needs d, nx, ny`);
  }
  if (pictures.some(q => q.id === p.id)) problems.push(`${where} picture id ${p.id} is used twice`);
  const counts = p.palette.map((_, i) => p.regions.filter(r => r.c === i).length);
  counts.forEach((n, i) => { if (n === 0) problems.push(`${where} colour ${i + 1} has no cells`); });
  // a flask gives 2 paint: a colour with fewer than 4 cells wastes paint (design rule), worth a warning only
  const few = counts.map((n, i) => n < 4 ? `${i + 1}:${n}` : '').filter(Boolean);
  pictures.push({ id: p.id, name: p.name, palette: p.palette, regions: p.regions,
    decorBack: p.decorBack || [], decorFront: p.decorFront || [], counts });
  console.log(`${f} ${p.id} cells ${p.regions.length} per colour ${counts.join('/')}${few.length ? '  (fewer than 4 cells: colour ' + few.join(', ') + ')' : ''}`);
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
writeFileSync(new URL('../js/pictures.js', import.meta.url),
  '// Generated by tools/build-pictures.mjs from pictures/*.json — edit those files, not this one.\nwindow.PICTURES = ' + JSON.stringify(pictures) + ';\n');
